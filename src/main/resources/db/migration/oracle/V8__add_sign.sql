CREATE TABLE BIZ_SIGN_RECORD_ (
    ID_ VARCHAR2(64 CHAR) NOT NULL,
    SIGN_ROUND_ID_ VARCHAR2(64 CHAR) NOT NULL,
    PROC_INST_ID_ VARCHAR2(64 CHAR) NOT NULL,
    SUB_PROC_INST_ID_ VARCHAR2(64 CHAR),
    SOURCE_TASK_ID_ VARCHAR2(64 CHAR) NOT NULL,
    SOURCE_TASK_DEF_KEY_ VARCHAR2(128 CHAR),
    SOURCE_ACT_INST_ID_ VARCHAR2(64 CHAR),
    SIGN_TYPE_ VARCHAR2(32 CHAR) NOT NULL,
    SIGN_MODE_ VARCHAR2(32 CHAR),
    APPROVE_MODE_ VARCHAR2(16 CHAR),
    INITIATOR_ID_ VARCHAR2(64 CHAR) NOT NULL,
    ADD_USER_ID_ VARCHAR2(64 CHAR) NOT NULL,
    ADD_TASK_ID_ VARCHAR2(64 CHAR),
    ADD_ACT_INST_ID_ VARCHAR2(64 CHAR),
    SIGN_STATUS_ VARCHAR2(32 CHAR) DEFAULT 'PENDING',
    OPINION_ VARCHAR2(2000 CHAR),
    SEQUENCE_NO_ NUMBER(10),
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FINISH_TIME_ TIMESTAMP,
    CONSTRAINT PK_BIZ_SIGN_RECORD_ PRIMARY KEY (ID_)
);

CREATE INDEX IDX_BIZ_SIGN_SOURCE ON BIZ_SIGN_RECORD_ (SOURCE_TASK_ID_, SIGN_STATUS_);
CREATE INDEX IDX_BIZ_SIGN_PROC ON BIZ_SIGN_RECORD_ (PROC_INST_ID_);
CREATE INDEX IDX_BIZ_SIGN_ROUND ON BIZ_SIGN_RECORD_ (SIGN_ROUND_ID_);
CREATE INDEX IDX_BIZ_SIGN_ADD_TASK ON BIZ_SIGN_RECORD_ (ADD_TASK_ID_);
CREATE INDEX IDX_BIZ_SIGN_SUB_PROC ON BIZ_SIGN_RECORD_ (SUB_PROC_INST_ID_);

COMMIT;
