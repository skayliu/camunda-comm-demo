-- ============================================================================
-- V1 基线 · Oracle 19c
--
-- 与 H2 版的三处实质差异：
--   1. 没有 CREATE TABLE IF NOT EXISTS —— Oracle 19c 不支持该语法（23c 才有），
--      幂等性完全交给 Flyway 版本表；DBA 手工执行前请先确认表不存在。
--   2. 字符长度用 CHAR 语义：VARCHAR2(64) 默认按字节算，AL32UTF8 下中文占 3 字节，
--      写 VARCHAR2(64 CHAR) 才能保证「64 个字符」，否则中文名字会被 21 字符截断。
--   3. INT 统一写 NUMBER(10)：Oracle 的 INT 是 NUMBER(38) 的别名，索引列用 38 位精度没有意义。
--
-- 标识符长度：索引名全部 ≤ 30 字符，兼容 Oracle 12.1 的旧限制（19c 放宽到 128）。
-- 空串语义：Oracle 中 '' 等于 NULL，所以 STATUS_ 这类列必须 NOT NULL + DEFAULT 双重约束。
-- ============================================================================

CREATE TABLE BIZ_TASK_EXT_ (
    ID_ VARCHAR2(64 CHAR) NOT NULL,
    TASK_ID_ VARCHAR2(64 CHAR) NOT NULL,
    PROC_INST_ID_ VARCHAR2(64 CHAR),
    ASSIGNEE_ VARCHAR2(64 CHAR),
    BIZ_STATUS_ VARCHAR2(20 CHAR) DEFAULT 'NORMAL' NOT NULL,
    ACTIVE_SESSION_ID_ VARCHAR2(64 CHAR),
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_BIZ_TASK_EXT_ PRIMARY KEY (ID_),
    CONSTRAINT UK_BIZ_TASK_EXT_TASK UNIQUE (TASK_ID_)
);

CREATE TABLE BIZ_COMM_SESSION_ (
    ID_ VARCHAR2(64 CHAR) NOT NULL,
    ROOT_TASK_ID_ VARCHAR2(64 CHAR) NOT NULL,
    INITIATOR_ VARCHAR2(64 CHAR) NOT NULL,
    INITIAL_CONTENT_ CLOB,
    STATUS_ VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CURRENT_ROUND_ NUMBER(10) DEFAULT 1,
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FINISH_TIME_ TIMESTAMP,
    CONSTRAINT PK_BIZ_COMM_SESSION_ PRIMARY KEY (ID_)
);

CREATE TABLE BIZ_COMM_TASK_ (
    ID_ VARCHAR2(64 CHAR) NOT NULL,
    SESSION_ID_ VARCHAR2(64 CHAR) NOT NULL,
    PARENT_COMM_TASK_ID_ VARCHAR2(64 CHAR),
    SOURCE_TASK_ID_ VARCHAR2(64 CHAR) NOT NULL,
    ROOT_TASK_ID_ VARCHAR2(64 CHAR) NOT NULL,
    SOURCE_TASK_DEF_KEY_ VARCHAR2(64 CHAR),
    TARGET_TYPE_ VARCHAR2(16 CHAR) NOT NULL,
    TARGET_ID_ VARCHAR2(64 CHAR) NOT NULL,
    TARGET_NAME_ VARCHAR2(128 CHAR),
    CONTENT_ CLOB,
    STATUS_ VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
    REPLY_CONTENT_ CLOB,
    REPLY_USER_ID_ VARCHAR2(64 CHAR),
    REPLY_TIME_ TIMESTAMP,
    WITHDRAW_TIME_ TIMESTAMP,
    -- 沟通旁路任务 ID：收回 / 反馈 / 待办反查的唯一关联键
    CAMUNDA_TASK_ID_ VARCHAR2(64 CHAR),
    -- 部门沟通子流程实例 ID：TARGET_TYPE_ = DEPT 时写入，收回与主流程结束级联终止据此定位整个子流程
    DEPT_PROC_INST_ID_ VARCHAR2(64 CHAR),
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_BIZ_COMM_TASK_ PRIMARY KEY (ID_)
);

CREATE TABLE BIZ_TASK_TRANSFER_ (
    ID_ VARCHAR2(64 CHAR) NOT NULL,
    TASK_ID_ VARCHAR2(64 CHAR) NOT NULL,
    PROC_INST_ID_ VARCHAR2(64 CHAR),
    TASK_DEF_KEY_ VARCHAR2(64 CHAR),
    TASK_NAME_ VARCHAR2(255 CHAR),
    FROM_USER_ID_ VARCHAR2(64 CHAR) NOT NULL,
    TO_USER_ID_ VARCHAR2(64 CHAR) NOT NULL,
    REASON_ VARCHAR2(500 CHAR),
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_BIZ_TASK_TRANSFER_ PRIMARY KEY (ID_)
);
