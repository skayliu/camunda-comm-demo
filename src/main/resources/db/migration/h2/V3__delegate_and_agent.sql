-- ============================================================================
-- V3 委托与代理 · H2 2.2
--
-- BIZ_TASK_DELEGATE_：一次委托的生命周期（PENDING → RESOLVED / CANCELED）。
--   人工委托与代理规则自动委托共用这张表，用 SOURCE_ 区分、AGENT_RULE_ID_ 指向规则。
-- BIZ_AGENT_RULE_：代理配置（谁在什么时间段、什么流程范围内代理给谁）。
--
-- 与转办表的区别：转办是责任转移（只追加、不改状态），
-- 委托是可逆的（同一任务可多次委托），所以这里维护 STATUS_ 而不是纯流水。
-- ============================================================================

CREATE TABLE IF NOT EXISTS BIZ_TASK_DELEGATE_ (
    ID_ VARCHAR(64) NOT NULL,
    TASK_ID_ VARCHAR(64) NOT NULL,
    PROC_INST_ID_ VARCHAR(64),
    TASK_DEF_KEY_ VARCHAR(64),
    TASK_NAME_ VARCHAR(255),
    -- 委托人 = 委托发生时的原办理人（引擎 OWNER_）
    OWNER_USER_ID_ VARCHAR(64) NOT NULL,
    -- 受托人 = 委托发生时的实际办理人（引擎 ASSIGNEE_）
    DELEGATE_USER_ID_ VARCHAR(64) NOT NULL,
    -- MANUAL 人工委托 / AGENT 代理规则自动委托
    SOURCE_ VARCHAR(16) NOT NULL DEFAULT 'MANUAL',
    AGENT_RULE_ID_ VARCHAR(64),
    REASON_ VARCHAR(500),
    -- PENDING 委托中 / RESOLVED 受托人交回 / CANCELED 委托人收回
    STATUS_ VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    -- 受托人的代办意见：与最终审批意见分开存储，前者是建议，后者是决策
    RESOLVE_CONTENT_ CLOB,
    RESOLVE_TIME_ TIMESTAMP,
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_BIZ_TASK_DELEGATE_ PRIMARY KEY (ID_)
);

CREATE TABLE IF NOT EXISTS BIZ_AGENT_RULE_ (
    ID_ VARCHAR(64) NOT NULL,
    OWNER_USER_ID_ VARCHAR(64) NOT NULL,
    AGENT_USER_ID_ VARCHAR(64) NOT NULL,
    START_TIME_ TIMESTAMP NOT NULL,
    END_TIME_ TIMESTAMP NOT NULL,
    -- 逗号分隔的流程定义 key，空表示全部流程
    PROCESS_DEFINITION_KEYS_ VARCHAR(1000),
    IS_ENABLED_ INT NOT NULL DEFAULT 1,
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_BIZ_AGENT_RULE_ PRIMARY KEY (ID_)
);

-- 委托链按任务回看 / 按委托人、受托人查列表
CREATE INDEX IF NOT EXISTS IDX_BIZ_DELEGATE_TASK_TIME ON BIZ_TASK_DELEGATE_ (TASK_ID_, CREATE_TIME_);
CREATE INDEX IF NOT EXISTS IDX_BIZ_DELEGATE_OWNER_TIME ON BIZ_TASK_DELEGATE_ (OWNER_USER_ID_, CREATE_TIME_);
CREATE INDEX IF NOT EXISTS IDX_BIZ_DELEGATE_TGT_STATUS ON BIZ_TASK_DELEGATE_ (DELEGATE_USER_ID_, STATUS_);
-- 任务创建时按 owner 找生效规则
CREATE INDEX IF NOT EXISTS IDX_BIZ_AGENT_OWNER_ENABLED ON BIZ_AGENT_RULE_ (OWNER_USER_ID_, IS_ENABLED_);
