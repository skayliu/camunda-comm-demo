-- ============================================================================
-- V6 传阅与阅办 · H2 2.2
--
-- BIZ_CC_RECORD_：传阅记录。传阅只做“送达”，不建引擎任务、不阻塞流程。
-- BIZ_HANDLE_RECORD_：阅办（承办）记录。有办理时限与结果，同样不进引擎执行链。
--
-- 只建业务扩展表，ACT_* 引擎表由 Camunda 自己管理；表之间不加外键。
-- ============================================================================

CREATE TABLE IF NOT EXISTS BIZ_CC_RECORD_ (
    ID_ VARCHAR(64) NOT NULL,
    PROC_INST_ID_ VARCHAR(64) NOT NULL,
    TASK_ID_ VARCHAR(64),
    PROC_DEF_KEY_ VARCHAR(128),
    TASK_DEF_KEY_ VARCHAR(128),
    TITLE_ VARCHAR(512),
    CC_USER_ID_ VARCHAR(64) NOT NULL,
    SENDER_USER_ID_ VARCHAR(64),
    -- NODE 节点传阅 / INST 流程传阅 / MANUAL 手动传阅
    CC_TYPE_ VARCHAR(32) DEFAULT 'NODE',
    IS_READ_ SMALLINT DEFAULT 0,
    READ_TIME_ TIMESTAMP,
    -- 软删除：0 正常 / 1 已撤回或已失效，保留审计痕迹
    IS_REVOKED_ SMALLINT DEFAULT 0,
    REVOKE_TIME_ TIMESTAMP,
    -- REVOKED 主动撤回 / INVALID 流程驳回、撤回或结束导致失效
    REVOKE_REASON_ VARCHAR(64),
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_BIZ_CC_RECORD_ PRIMARY KEY (ID_)
);

CREATE TABLE IF NOT EXISTS BIZ_HANDLE_RECORD_ (
    ID_ VARCHAR(64) NOT NULL,
    PROC_INST_ID_ VARCHAR(64) NOT NULL,
    TASK_ID_ VARCHAR(64),
    PROC_DEF_KEY_ VARCHAR(128),
    TASK_DEF_KEY_ VARCHAR(128),
    TITLE_ VARCHAR(512),
    ASSIGNEE_ID_ VARCHAR(64) NOT NULL,
    SENDER_ID_ VARCHAR(64) NOT NULL,
    INSTRUCTION_ CLOB,
    DEADLINE_ TIMESTAMP,
    -- PENDING 待阅 / HANDLING 办理中 / DONE 已完成 / OVERDUE 逾期
    HANDLE_STATUS_ VARCHAR(32) DEFAULT 'PENDING',
    HANDLE_RESULT_ CLOB,
    HANDLE_TIME_ TIMESTAMP,
    IS_REVOKED_ SMALLINT DEFAULT 0,
    REVOKE_TIME_ TIMESTAMP,
    REVOKE_REASON_ VARCHAR(64),
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_BIZ_HANDLE_RECORD_ PRIMARY KEY (ID_)
);

-- 我的待阅：按人 + 已读状态查未读列表
CREATE INDEX IF NOT EXISTS IDX_BIZ_CC_USER_READ ON BIZ_CC_RECORD_ (CC_USER_ID_, IS_READ_, IS_REVOKED_);
CREATE INDEX IF NOT EXISTS IDX_BIZ_CC_PROC ON BIZ_CC_RECORD_ (PROC_INST_ID_);
-- 去重：同一流程实例下同一个人只保留一条有效传阅
CREATE INDEX IF NOT EXISTS IDX_BIZ_CC_PROC_USER ON BIZ_CC_RECORD_ (PROC_INST_ID_, CC_USER_ID_);

-- 我的承办：按人 + 状态查待办
CREATE INDEX IF NOT EXISTS IDX_BIZ_HANDLE_ASSIGNEE ON BIZ_HANDLE_RECORD_ (ASSIGNEE_ID_, HANDLE_STATUS_, IS_REVOKED_);
CREATE INDEX IF NOT EXISTS IDX_BIZ_HANDLE_PROC ON BIZ_HANDLE_RECORD_ (PROC_INST_ID_);
-- 逾期扫描：按截止时间过滤
CREATE INDEX IF NOT EXISTS IDX_BIZ_HANDLE_DEADLINE ON BIZ_HANDLE_RECORD_ (DEADLINE_, HANDLE_STATUS_);
