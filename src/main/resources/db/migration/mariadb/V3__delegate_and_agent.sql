-- 与 MySQL 8 版基本一致：DATETIME(3) + LONGTEXT + utf8mb4。
-- MariaDB 支持 CREATE INDEX IF NOT EXISTS，但为了与 MySQL 版逐行一致（便于比对），
-- 这里同样不写幂等语法，统一由 Flyway 版本表保证只执行一次。
