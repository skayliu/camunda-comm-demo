CREATE TABLE BIZ_TASK_DELEGATE_ (
    ID_ VARCHAR(64 OCTETS) NOT NULL,
    TASK_ID_ VARCHAR(64 OCTETS) NOT NULL,
    PROC_INST_ID_ VARCHAR(64 OCTETS),
    TASK_DEF_KEY_ VARCHAR(64 OCTETS),
    TASK_NAME_ VARCHAR(255 OCTETS),
    OWNER_USER_ID_ VARCHAR(64 OCTETS) NOT NULL,
    DELEGATE_USER_ID_ VARCHAR(64 OCTETS) NOT NULL,
    SOURCE_ VARCHAR(16 OCTETS) NOT NULL DEFAULT 'MANUAL',
    AGENT_RULE_ID_ VARCHAR(64 OCTETS),
    REASON_ VARCHAR(500 OCTETS),
    STATUS_ VARCHAR(20 OCTETS) NOT NULL DEFAULT 'PENDING',
    RESOLVE_CONTENT_ CLOB,
    RESOLVE_TIME_ TIMESTAMP,
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_BIZ_TASK_DELEGATE_ PRIMARY KEY (ID_)
);

CREATE TABLE BIZ_AGENT_RULE_ (
    ID_ VARCHAR(64 OCTETS) NOT NULL,
    OWNER_USER_ID_ VARCHAR(64 OCTETS) NOT NULL,
    AGENT_USER_ID_ VARCHAR(64 OCTETS) NOT NULL,
    START_TIME_ TIMESTAMP NOT NULL,
    END_TIME_ TIMESTAMP NOT NULL,
    PROCESS_DEFINITION_KEYS_ VARCHAR(1000 OCTETS),
    IS_ENABLED_ SMALLINT NOT NULL DEFAULT 1,
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_BIZ_AGENT_RULE_ PRIMARY KEY (ID_)
);

CREATE INDEX IDX_BIZ_DELEGATE_TASK_TIME ON BIZ_TASK_DELEGATE_ (TASK_ID_, CREATE_TIME_);
CREATE INDEX IDX_BIZ_DELEGATE_OWNER_TIME ON BIZ_TASK_DELEGATE_ (OWNER_USER_ID_, CREATE_TIME_);
CREATE INDEX IDX_BIZ_DELEGATE_TGT_STATUS ON BIZ_TASK_DELEGATE_ (DELEGATE_USER_ID_, STATUS_);
CREATE INDEX IDX_BIZ_AGENT_OWNER_ENABLED ON BIZ_AGENT_RULE_ (OWNER_USER_ID_, IS_ENABLED_);
