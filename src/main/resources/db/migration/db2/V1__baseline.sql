-- ============================================================================
-- V1 基线 · IBM DB2 11.5（LUW）
--
-- 与 H2 版的差异：
--   1. 没有 CREATE TABLE IF NOT EXISTS，幂等性交给 Flyway 版本表；
--   2. VARCHAR(n) 默认按字节计（OCTETS），ID 类列存 ASCII 足够；
--      可能含中文的列显式写 CODEUNITS32，保证「128 个字符」而不是「128 字节」；
--   3. 字符串默认值仍用单引号，DB2 不做 Oracle 那种空串等于 NULL 的转换。
--
-- 表与索引都会落在当前用户的默认表空间；生产库请让 DBA 在脚本前 SET CURRENT SCHEMA，
-- 或用 Flyway 的 schemas 配置指定 schema，避免建到实例默认 schema 下。
-- ============================================================================

CREATE TABLE BIZ_TASK_EXT_ (
    ID_ VARCHAR(64 OCTETS) NOT NULL,
    TASK_ID_ VARCHAR(64 OCTETS) NOT NULL,
    PROC_INST_ID_ VARCHAR(64 OCTETS),
    ASSIGNEE_ VARCHAR(64 OCTETS),
    BIZ_STATUS_ VARCHAR(20 OCTETS) NOT NULL DEFAULT 'NORMAL',
    ACTIVE_SESSION_ID_ VARCHAR(64 OCTETS),
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_BIZ_TASK_EXT_ PRIMARY KEY (ID_),
    CONSTRAINT UK_BIZ_TASK_EXT_TASK UNIQUE (TASK_ID_)
);

CREATE TABLE BIZ_COMM_SESSION_ (
    ID_ VARCHAR(64 OCTETS) NOT NULL,
    ROOT_TASK_ID_ VARCHAR(64 OCTETS) NOT NULL,
    INITIATOR_ VARCHAR(64 OCTETS) NOT NULL,
    INITIAL_CONTENT_ CLOB,
    STATUS_ VARCHAR(20 OCTETS) NOT NULL DEFAULT 'ACTIVE',
    CURRENT_ROUND_ INT DEFAULT 1,
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FINISH_TIME_ TIMESTAMP,
    CONSTRAINT PK_BIZ_COMM_SESSION_ PRIMARY KEY (ID_)
);

CREATE TABLE BIZ_COMM_TASK_ (
    ID_ VARCHAR(64 OCTETS) NOT NULL,
    SESSION_ID_ VARCHAR(64 OCTETS) NOT NULL,
    PARENT_COMM_TASK_ID_ VARCHAR(64 OCTETS),
    SOURCE_TASK_ID_ VARCHAR(64 OCTETS) NOT NULL,
    ROOT_TASK_ID_ VARCHAR(64 OCTETS) NOT NULL,
    SOURCE_TASK_DEF_KEY_ VARCHAR(64 OCTETS),
    TARGET_TYPE_ VARCHAR(16 OCTETS) NOT NULL,
    TARGET_ID_ VARCHAR(64 OCTETS) NOT NULL,
    TARGET_NAME_ VARCHAR(128 CODEUNITS32),
    CONTENT_ CLOB,
    STATUS_ VARCHAR(20 OCTETS) NOT NULL DEFAULT 'PENDING',
    REPLY_CONTENT_ CLOB,
    REPLY_USER_ID_ VARCHAR(64 OCTETS),
    REPLY_TIME_ TIMESTAMP,
    WITHDRAW_TIME_ TIMESTAMP,
    -- 沟通旁路任务 ID：收回 / 反馈 / 待办反查的唯一关联键
    CAMUNDA_TASK_ID_ VARCHAR(64 OCTETS),
    -- 部门沟通子流程实例 ID：TARGET_TYPE_ = DEPT 时写入，收回与主流程结束级联终止据此定位整个子流程
    DEPT_PROC_INST_ID_ VARCHAR(64 OCTETS),
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_BIZ_COMM_TASK_ PRIMARY KEY (ID_)
);

CREATE TABLE BIZ_TASK_TRANSFER_ (
    ID_ VARCHAR(64 OCTETS) NOT NULL,
    TASK_ID_ VARCHAR(64 OCTETS) NOT NULL,
    PROC_INST_ID_ VARCHAR(64 OCTETS),
    TASK_DEF_KEY_ VARCHAR(64 OCTETS),
    TASK_NAME_ VARCHAR(255 CODEUNITS32),
    FROM_USER_ID_ VARCHAR(64 OCTETS) NOT NULL,
    TO_USER_ID_ VARCHAR(64 OCTETS) NOT NULL,
    REASON_ VARCHAR(500 CODEUNITS32),
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_BIZ_TASK_TRANSFER_ PRIMARY KEY (ID_)
);
