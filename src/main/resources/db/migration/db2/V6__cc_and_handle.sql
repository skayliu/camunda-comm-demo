-- ============================================================================
-- V6 传阅与阅办 · DB2 11.5 LUW
-- 与 H2 版的差异：无 IF NOT EXISTS、VARCHAR(n OCTETS) 按字节计长、布尔列用 SMALLINT。
-- 标题按 UTF-8 中文 3 字节预留：1536 OCTETS ≈ 512 字符。
-- ============================================================================

CREATE TABLE BIZ_CC_RECORD_ (
    ID_ VARCHAR(64 OCTETS) NOT NULL,
    PROC_INST_ID_ VARCHAR(64 OCTETS) NOT NULL,
    TASK_ID_ VARCHAR(64 OCTETS),
    PROC_DEF_KEY_ VARCHAR(128 OCTETS),
    TASK_DEF_KEY_ VARCHAR(128 OCTETS),
    TITLE_ VARCHAR(1536 OCTETS),
    CC_USER_ID_ VARCHAR(64 OCTETS) NOT NULL,
    SENDER_USER_ID_ VARCHAR(64 OCTETS),
    CC_TYPE_ VARCHAR(32 OCTETS) DEFAULT 'NODE',
    IS_READ_ SMALLINT DEFAULT 0,
    READ_TIME_ TIMESTAMP,
    IS_REVOKED_ SMALLINT DEFAULT 0,
    REVOKE_TIME_ TIMESTAMP,
    REVOKE_REASON_ VARCHAR(64 OCTETS),
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_BIZ_CC_RECORD_ PRIMARY KEY (ID_)
);

CREATE TABLE BIZ_HANDLE_RECORD_ (
    ID_ VARCHAR(64 OCTETS) NOT NULL,
    PROC_INST_ID_ VARCHAR(64 OCTETS) NOT NULL,
    TASK_ID_ VARCHAR(64 OCTETS),
    PROC_DEF_KEY_ VARCHAR(128 OCTETS),
    TASK_DEF_KEY_ VARCHAR(128 OCTETS),
    TITLE_ VARCHAR(1536 OCTETS),
    ASSIGNEE_ID_ VARCHAR(64 OCTETS) NOT NULL,
    SENDER_ID_ VARCHAR(64 OCTETS) NOT NULL,
    INSTRUCTION_ CLOB,
    DEADLINE_ TIMESTAMP,
    HANDLE_STATUS_ VARCHAR(32 OCTETS) DEFAULT 'PENDING',
    HANDLE_RESULT_ CLOB,
    HANDLE_TIME_ TIMESTAMP,
    IS_REVOKED_ SMALLINT DEFAULT 0,
    REVOKE_TIME_ TIMESTAMP,
    REVOKE_REASON_ VARCHAR(64 OCTETS),
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_BIZ_HANDLE_RECORD_ PRIMARY KEY (ID_)
);

CREATE INDEX IDX_BIZ_CC_USER_READ ON BIZ_CC_RECORD_ (CC_USER_ID_, IS_READ_, IS_REVOKED_);
CREATE INDEX IDX_BIZ_CC_PROC ON BIZ_CC_RECORD_ (PROC_INST_ID_);
CREATE INDEX IDX_BIZ_CC_PROC_USER ON BIZ_CC_RECORD_ (PROC_INST_ID_, CC_USER_ID_);

CREATE INDEX IDX_BIZ_HANDLE_ASSIGNEE ON BIZ_HANDLE_RECORD_ (ASSIGNEE_ID_, HANDLE_STATUS_, IS_REVOKED_);
CREATE INDEX IDX_BIZ_HANDLE_PROC ON BIZ_HANDLE_RECORD_ (PROC_INST_ID_);
CREATE INDEX IDX_BIZ_HANDLE_DEADLINE ON BIZ_HANDLE_RECORD_ (DEADLINE_, HANDLE_STATUS_);
