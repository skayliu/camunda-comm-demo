CREATE TABLE BIZ_SIGN_RECORD_ (
    ID_ NVARCHAR(64) NOT NULL,
    SIGN_ROUND_ID_ NVARCHAR(64) NOT NULL,
    PROC_INST_ID_ NVARCHAR(64) NOT NULL,
    SUB_PROC_INST_ID_ NVARCHAR(64) NULL,
    SOURCE_TASK_ID_ NVARCHAR(64) NOT NULL,
    SOURCE_TASK_DEF_KEY_ NVARCHAR(128) NULL,
    SOURCE_ACT_INST_ID_ NVARCHAR(64) NULL,
    SIGN_TYPE_ NVARCHAR(32) NOT NULL,
    SIGN_MODE_ NVARCHAR(32) NULL,
    APPROVE_MODE_ NVARCHAR(16) NULL,
    INITIATOR_ID_ NVARCHAR(64) NOT NULL,
    ADD_USER_ID_ NVARCHAR(64) NOT NULL,
    ADD_TASK_ID_ NVARCHAR(64) NULL,
    ADD_ACT_INST_ID_ NVARCHAR(64) NULL,
    SIGN_STATUS_ NVARCHAR(32) NULL CONSTRAINT DF_BIZ_SIGN_STATUS DEFAULT N'PENDING',
    OPINION_ NVARCHAR(2000) NULL,
    SEQUENCE_NO_ INT NULL,
    CREATE_TIME_ DATETIME2(3) NULL CONSTRAINT DF_BIZ_SIGN_CT DEFAULT SYSDATETIME(),
    UPDATE_TIME_ DATETIME2(3) NULL CONSTRAINT DF_BIZ_SIGN_UT DEFAULT SYSDATETIME(),
    FINISH_TIME_ DATETIME2(3) NULL,
    CONSTRAINT PK_BIZ_SIGN_RECORD_ PRIMARY KEY (ID_)
);

CREATE INDEX IDX_BIZ_SIGN_SOURCE ON BIZ_SIGN_RECORD_ (SOURCE_TASK_ID_, SIGN_STATUS_);
CREATE INDEX IDX_BIZ_SIGN_PROC ON BIZ_SIGN_RECORD_ (PROC_INST_ID_);
CREATE INDEX IDX_BIZ_SIGN_ROUND ON BIZ_SIGN_RECORD_ (SIGN_ROUND_ID_);
CREATE INDEX IDX_BIZ_SIGN_ADD_TASK ON BIZ_SIGN_RECORD_ (ADD_TASK_ID_);
CREATE INDEX IDX_BIZ_SIGN_SUB_PROC ON BIZ_SIGN_RECORD_ (SUB_PROC_INST_ID_);
