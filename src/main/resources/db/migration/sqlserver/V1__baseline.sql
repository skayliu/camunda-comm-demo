-- ============================================================================
-- V1 基线 · SQL Server 2017 / 2019 / 2022
--
-- 这个方言有两个必须改、改了才会被发现的坑：
--   1. 绝不能写 TIMESTAMP —— SQL Server 的 TIMESTAMP 是 rowversion（8 字节二进制版本号），
--      不是日期时间。用 DATETIME2(3) 才有毫秒精度的真实时间。
--   2. 没有 CREATE TABLE IF NOT EXISTS。幂等性交给 Flyway 版本表；
--      默认约束必须显式命名，否则同名约束在库里重复会报「对象名已存在」。
--
-- 字符串统一 NVARCHAR：业务侧中文名、沟通正文都可能出现非 ASCII 字符，
-- VARCHAR 在非 UTF-8 排序规则下会变成问号，而 NVARCHAR 永远按 UTF-16 存储。
-- ============================================================================

CREATE TABLE BIZ_TASK_EXT_ (
    ID_ NVARCHAR(64) NOT NULL,
    TASK_ID_ NVARCHAR(64) NOT NULL,
    PROC_INST_ID_ NVARCHAR(64) NULL,
    ASSIGNEE_ NVARCHAR(64) NULL,
    BIZ_STATUS_ NVARCHAR(20) NOT NULL CONSTRAINT DF_BIZ_TASK_EXT_STATUS DEFAULT N'NORMAL',
    ACTIVE_SESSION_ID_ NVARCHAR(64) NULL,
    CREATE_TIME_ DATETIME2(3) NULL CONSTRAINT DF_BIZ_TASK_EXT_CT DEFAULT SYSDATETIME(),
    UPDATE_TIME_ DATETIME2(3) NULL CONSTRAINT DF_BIZ_TASK_EXT_UT DEFAULT SYSDATETIME(),
    CONSTRAINT PK_BIZ_TASK_EXT_ PRIMARY KEY (ID_),
    CONSTRAINT UK_BIZ_TASK_EXT_TASK UNIQUE (TASK_ID_)
);

CREATE TABLE BIZ_COMM_SESSION_ (
    ID_ NVARCHAR(64) NOT NULL,
    ROOT_TASK_ID_ NVARCHAR(64) NOT NULL,
    INITIATOR_ NVARCHAR(64) NOT NULL,
    INITIAL_CONTENT_ NVARCHAR(MAX) NULL,
    STATUS_ NVARCHAR(20) NOT NULL CONSTRAINT DF_BIZ_COMM_SESSION_STATUS DEFAULT N'ACTIVE',
    CURRENT_ROUND_ INT NULL CONSTRAINT DF_BIZ_COMM_SESSION_ROUND DEFAULT 1,
    CREATE_TIME_ DATETIME2(3) NULL CONSTRAINT DF_BIZ_COMM_SESSION_CT DEFAULT SYSDATETIME(),
    FINISH_TIME_ DATETIME2(3) NULL,
    CONSTRAINT PK_BIZ_COMM_SESSION_ PRIMARY KEY (ID_)
);

CREATE TABLE BIZ_COMM_TASK_ (
    ID_ NVARCHAR(64) NOT NULL,
    SESSION_ID_ NVARCHAR(64) NOT NULL,
    PARENT_COMM_TASK_ID_ NVARCHAR(64) NULL,
    SOURCE_TASK_ID_ NVARCHAR(64) NOT NULL,
    ROOT_TASK_ID_ NVARCHAR(64) NOT NULL,
    SOURCE_TASK_DEF_KEY_ NVARCHAR(64) NULL,
    TARGET_TYPE_ NVARCHAR(16) NOT NULL,
    TARGET_ID_ NVARCHAR(64) NOT NULL,
    TARGET_NAME_ NVARCHAR(128) NULL,
    CONTENT_ NVARCHAR(MAX) NULL,
    STATUS_ NVARCHAR(20) NOT NULL CONSTRAINT DF_BIZ_COMM_TASK_STATUS DEFAULT N'PENDING',
    REPLY_CONTENT_ NVARCHAR(MAX) NULL,
    REPLY_USER_ID_ NVARCHAR(64) NULL,
    REPLY_TIME_ DATETIME2(3) NULL,
    WITHDRAW_TIME_ DATETIME2(3) NULL,
    -- 沟通旁路任务 ID：收回 / 反馈 / 待办反查的唯一关联键
    CAMUNDA_TASK_ID_ NVARCHAR(64) NULL,
    -- 部门沟通子流程实例 ID：预留给 DEPT 类型，当前恒为 NULL
    DEPT_PROC_INST_ID_ NVARCHAR(64) NULL,
    CREATE_TIME_ DATETIME2(3) NULL CONSTRAINT DF_BIZ_COMM_TASK_CT DEFAULT SYSDATETIME(),
    CONSTRAINT PK_BIZ_COMM_TASK_ PRIMARY KEY (ID_)
);

CREATE TABLE BIZ_TASK_TRANSFER_ (
    ID_ NVARCHAR(64) NOT NULL,
    TASK_ID_ NVARCHAR(64) NOT NULL,
    PROC_INST_ID_ NVARCHAR(64) NULL,
    TASK_DEF_KEY_ NVARCHAR(64) NULL,
    TASK_NAME_ NVARCHAR(255) NULL,
    FROM_USER_ID_ NVARCHAR(64) NOT NULL,
    TO_USER_ID_ NVARCHAR(64) NOT NULL,
    REASON_ NVARCHAR(500) NULL,
    CREATE_TIME_ DATETIME2(3) NULL CONSTRAINT DF_BIZ_TASK_TRANSFER_CT DEFAULT SYSDATETIME(),
    CONSTRAINT PK_BIZ_TASK_TRANSFER_ PRIMARY KEY (ID_)
);
