CREATE TABLE BIZ_TASK_DELEGATE_ (
    ID_ NVARCHAR(64) NOT NULL,
    TASK_ID_ NVARCHAR(64) NOT NULL,
    PROC_INST_ID_ NVARCHAR(64) NULL,
    TASK_DEF_KEY_ NVARCHAR(64) NULL,
    TASK_NAME_ NVARCHAR(255) NULL,
    OWNER_USER_ID_ NVARCHAR(64) NOT NULL,
    DELEGATE_USER_ID_ NVARCHAR(64) NOT NULL,
    SOURCE_ NVARCHAR(16) NOT NULL CONSTRAINT DF_BIZ_DELEGATE_SOURCE DEFAULT N'MANUAL',
    AGENT_RULE_ID_ NVARCHAR(64) NULL,
    REASON_ NVARCHAR(500) NULL,
    STATUS_ NVARCHAR(20) NOT NULL CONSTRAINT DF_BIZ_DELEGATE_STATUS DEFAULT N'PENDING',
    RESOLVE_CONTENT_ NVARCHAR(MAX) NULL,
    RESOLVE_TIME_ DATETIME2(3) NULL,
    CREATE_TIME_ DATETIME2(3) NULL CONSTRAINT DF_BIZ_DELEGATE_CT DEFAULT SYSDATETIME(),
    UPDATE_TIME_ DATETIME2(3) NULL CONSTRAINT DF_BIZ_DELEGATE_UT DEFAULT SYSDATETIME(),
    CONSTRAINT PK_BIZ_TASK_DELEGATE_ PRIMARY KEY (ID_)
);

CREATE TABLE BIZ_AGENT_RULE_ (
    ID_ NVARCHAR(64) NOT NULL,
    OWNER_USER_ID_ NVARCHAR(64) NOT NULL,
    AGENT_USER_ID_ NVARCHAR(64) NOT NULL,
    START_TIME_ DATETIME2(3) NOT NULL,
    END_TIME_ DATETIME2(3) NOT NULL,
    PROCESS_DEFINITION_KEYS_ NVARCHAR(1000) NULL,
    IS_ENABLED_ TINYINT NOT NULL CONSTRAINT DF_BIZ_AGENT_ENABLED DEFAULT 1,
    CREATE_TIME_ DATETIME2(3) NULL CONSTRAINT DF_BIZ_AGENT_CT DEFAULT SYSDATETIME(),
    UPDATE_TIME_ DATETIME2(3) NULL CONSTRAINT DF_BIZ_AGENT_UT DEFAULT SYSDATETIME(),
    CONSTRAINT PK_BIZ_AGENT_RULE_ PRIMARY KEY (ID_)
);

CREATE INDEX IDX_BIZ_DELEGATE_TASK_TIME ON BIZ_TASK_DELEGATE_ (TASK_ID_, CREATE_TIME_);
CREATE INDEX IDX_BIZ_DELEGATE_OWNER_TIME ON BIZ_TASK_DELEGATE_ (OWNER_USER_ID_, CREATE_TIME_);
CREATE INDEX IDX_BIZ_DELEGATE_TGT_STATUS ON BIZ_TASK_DELEGATE_ (DELEGATE_USER_ID_, STATUS_);
CREATE INDEX IDX_BIZ_AGENT_OWNER_ENABLED ON BIZ_AGENT_RULE_ (OWNER_USER_ID_, IS_ENABLED_);
