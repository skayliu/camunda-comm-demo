CREATE TABLE BIZ_CC_RECORD_ (
    ID_ NVARCHAR(64) NOT NULL,
    PROC_INST_ID_ NVARCHAR(64) NOT NULL,
    TASK_ID_ NVARCHAR(64) NULL,
    PROC_DEF_KEY_ NVARCHAR(128) NULL,
    TASK_DEF_KEY_ NVARCHAR(128) NULL,
    TITLE_ NVARCHAR(512) NULL,
    CC_USER_ID_ NVARCHAR(64) NOT NULL,
    SENDER_USER_ID_ NVARCHAR(64) NULL,
    CC_TYPE_ NVARCHAR(32) NULL CONSTRAINT DF_BIZ_CC_TYPE DEFAULT N'NODE',
    IS_READ_ TINYINT NULL CONSTRAINT DF_BIZ_CC_READ DEFAULT 0,
    READ_TIME_ DATETIME2(3) NULL,
    IS_REVOKED_ TINYINT NULL CONSTRAINT DF_BIZ_CC_REVOKED DEFAULT 0,
    REVOKE_TIME_ DATETIME2(3) NULL,
    REVOKE_REASON_ NVARCHAR(64) NULL,
    CREATE_TIME_ DATETIME2(3) NULL CONSTRAINT DF_BIZ_CC_CT DEFAULT SYSDATETIME(),
    UPDATE_TIME_ DATETIME2(3) NULL CONSTRAINT DF_BIZ_CC_UT DEFAULT SYSDATETIME(),
    CONSTRAINT PK_BIZ_CC_RECORD_ PRIMARY KEY (ID_)
);

CREATE TABLE BIZ_HANDLE_RECORD_ (
    ID_ NVARCHAR(64) NOT NULL,
    PROC_INST_ID_ NVARCHAR(64) NOT NULL,
    TASK_ID_ NVARCHAR(64) NULL,
    PROC_DEF_KEY_ NVARCHAR(128) NULL,
    TASK_DEF_KEY_ NVARCHAR(128) NULL,
    TITLE_ NVARCHAR(512) NULL,
    ASSIGNEE_ID_ NVARCHAR(64) NOT NULL,
    SENDER_ID_ NVARCHAR(64) NOT NULL,
    INSTRUCTION_ NVARCHAR(MAX) NULL,
    DEADLINE_ DATETIME2(3) NULL,
    HANDLE_STATUS_ NVARCHAR(32) NULL CONSTRAINT DF_BIZ_HANDLE_STATUS DEFAULT N'PENDING',
    HANDLE_RESULT_ NVARCHAR(MAX) NULL,
    HANDLE_TIME_ DATETIME2(3) NULL,
    IS_REVOKED_ TINYINT NULL CONSTRAINT DF_BIZ_HANDLE_REVOKED DEFAULT 0,
    REVOKE_TIME_ DATETIME2(3) NULL,
    REVOKE_REASON_ NVARCHAR(64) NULL,
    CREATE_TIME_ DATETIME2(3) NULL CONSTRAINT DF_BIZ_HANDLE_CT DEFAULT SYSDATETIME(),
    UPDATE_TIME_ DATETIME2(3) NULL CONSTRAINT DF_BIZ_HANDLE_UT DEFAULT SYSDATETIME(),
    CONSTRAINT PK_BIZ_HANDLE_RECORD_ PRIMARY KEY (ID_)
);

CREATE INDEX IDX_BIZ_CC_USER_READ ON BIZ_CC_RECORD_ (CC_USER_ID_, IS_READ_, IS_REVOKED_);
CREATE INDEX IDX_BIZ_CC_PROC ON BIZ_CC_RECORD_ (PROC_INST_ID_);
CREATE INDEX IDX_BIZ_CC_PROC_USER ON BIZ_CC_RECORD_ (PROC_INST_ID_, CC_USER_ID_);

CREATE INDEX IDX_BIZ_HANDLE_ASSIGNEE ON BIZ_HANDLE_RECORD_ (ASSIGNEE_ID_, HANDLE_STATUS_, IS_REVOKED_);
CREATE INDEX IDX_BIZ_HANDLE_PROC ON BIZ_HANDLE_RECORD_ (PROC_INST_ID_);
CREATE INDEX IDX_BIZ_HANDLE_DEADLINE ON BIZ_HANDLE_RECORD_ (DEADLINE_, HANDLE_STATUS_);
