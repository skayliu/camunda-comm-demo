CREATE TABLE IF NOT EXISTS BIZ_SIGN_RECORD_ (
    ID_ VARCHAR(64) NOT NULL,
    SIGN_ROUND_ID_ VARCHAR(64) NOT NULL,
    PROC_INST_ID_ VARCHAR(64) NOT NULL,
    SUB_PROC_INST_ID_ VARCHAR(64) NULL,
    SOURCE_TASK_ID_ VARCHAR(64) NOT NULL,
    SOURCE_TASK_DEF_KEY_ VARCHAR(128) NULL,
    SOURCE_ACT_INST_ID_ VARCHAR(64) NULL,
    SIGN_TYPE_ VARCHAR(32) NOT NULL,
    SIGN_MODE_ VARCHAR(32) NULL,
    APPROVE_MODE_ VARCHAR(16) NULL,
    INITIATOR_ID_ VARCHAR(64) NOT NULL,
    ADD_USER_ID_ VARCHAR(64) NOT NULL,
    ADD_TASK_ID_ VARCHAR(64) NULL,
    ADD_ACT_INST_ID_ VARCHAR(64) NULL,
    SIGN_STATUS_ VARCHAR(32) DEFAULT 'PENDING',
    OPINION_ VARCHAR(2000) NULL,
    SEQUENCE_NO_ INT NULL,
    CREATE_TIME_ DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
    UPDATE_TIME_ DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
    FINISH_TIME_ DATETIME(3) NULL,
    CONSTRAINT PK_BIZ_SIGN_RECORD_ PRIMARY KEY (ID_),
    INDEX IDX_BIZ_SIGN_SOURCE (SOURCE_TASK_ID_, SIGN_STATUS_),
    INDEX IDX_BIZ_SIGN_PROC (PROC_INST_ID_),
    INDEX IDX_BIZ_SIGN_ROUND (SIGN_ROUND_ID_),
    INDEX IDX_BIZ_SIGN_ADD_TASK (ADD_TASK_ID_),
    INDEX IDX_BIZ_SIGN_SUB_PROC (SUB_PROC_INST_ID_)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;
