CREATE TABLE IF NOT EXISTS BIZ_CC_RECORD_ (
    ID_ VARCHAR(64) NOT NULL,
    PROC_INST_ID_ VARCHAR(64) NOT NULL,
    TASK_ID_ VARCHAR(64) NULL,
    PROC_DEF_KEY_ VARCHAR(128) NULL,
    TASK_DEF_KEY_ VARCHAR(128) NULL,
    TITLE_ VARCHAR(512) NULL,
    CC_USER_ID_ VARCHAR(64) NOT NULL,
    SENDER_USER_ID_ VARCHAR(64) NULL,
    CC_TYPE_ VARCHAR(32) DEFAULT 'NODE',
    IS_READ_ TINYINT DEFAULT 0,
    READ_TIME_ DATETIME(3) NULL,
    IS_REVOKED_ TINYINT DEFAULT 0,
    REVOKE_TIME_ DATETIME(3) NULL,
    REVOKE_REASON_ VARCHAR(64) NULL,
    CREATE_TIME_ DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
    UPDATE_TIME_ DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT PK_BIZ_CC_RECORD_ PRIMARY KEY (ID_),
    INDEX IDX_BIZ_CC_USER_READ (CC_USER_ID_, IS_READ_, IS_REVOKED_),
    INDEX IDX_BIZ_CC_PROC (PROC_INST_ID_),
    INDEX IDX_BIZ_CC_PROC_USER (PROC_INST_ID_, CC_USER_ID_)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE IF NOT EXISTS BIZ_HANDLE_RECORD_ (
    ID_ VARCHAR(64) NOT NULL,
    PROC_INST_ID_ VARCHAR(64) NOT NULL,
    TASK_ID_ VARCHAR(64) NULL,
    PROC_DEF_KEY_ VARCHAR(128) NULL,
    TASK_DEF_KEY_ VARCHAR(128) NULL,
    TITLE_ VARCHAR(512) NULL,
    ASSIGNEE_ID_ VARCHAR(64) NOT NULL,
    SENDER_ID_ VARCHAR(64) NOT NULL,
    INSTRUCTION_ TEXT NULL,
    DEADLINE_ DATETIME(3) NULL,
    HANDLE_STATUS_ VARCHAR(32) DEFAULT 'PENDING',
    HANDLE_RESULT_ TEXT NULL,
    HANDLE_TIME_ DATETIME(3) NULL,
    IS_REVOKED_ TINYINT DEFAULT 0,
    REVOKE_TIME_ DATETIME(3) NULL,
    REVOKE_REASON_ VARCHAR(64) NULL,
    CREATE_TIME_ DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
    UPDATE_TIME_ DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT PK_BIZ_HANDLE_RECORD_ PRIMARY KEY (ID_),
    INDEX IDX_BIZ_HANDLE_ASSIGNEE (ASSIGNEE_ID_, HANDLE_STATUS_, IS_REVOKED_),
    INDEX IDX_BIZ_HANDLE_PROC (PROC_INST_ID_),
    INDEX IDX_BIZ_HANDLE_DEADLINE (DEADLINE_, HANDLE_STATUS_)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;
