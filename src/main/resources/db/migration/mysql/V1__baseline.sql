-- ============================================================================
-- V1 基线 · MySQL 8.0（MariaDB 10.6+ 可直接复用本目录）
--
-- 与 H2 版的类型映射：
--   CLOB           → LONGTEXT（TEXT 只有 64KB，沟通正文可能超）
--   TIMESTAMP      → DATETIME(3)（TIMESTAMP 上限 2038-01-19，且受时区影响）
--   VARCHAR        → VARCHAR（utf8mb4 下 64 字符 = 256 字节，主键索引远低于 3072 字节上限）
--
-- 不加外键：业务表与引擎表同事务写入，引擎清理历史时外键会阻塞。
-- 索引不写在 V1，统一放在 V2，避免建表与建索引两条路径不一致。
-- ============================================================================

CREATE TABLE IF NOT EXISTS BIZ_TASK_EXT_ (
    ID_ VARCHAR(64) NOT NULL,
    TASK_ID_ VARCHAR(64) NOT NULL,
    PROC_INST_ID_ VARCHAR(64) NULL,
    ASSIGNEE_ VARCHAR(64) NULL,
    BIZ_STATUS_ VARCHAR(20) NOT NULL DEFAULT 'NORMAL',
    ACTIVE_SESSION_ID_ VARCHAR(64) NULL,
    CREATE_TIME_ DATETIME(3) NULL DEFAULT CURRENT_TIMESTAMP(3),
    UPDATE_TIME_ DATETIME(3) NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (ID_),
    UNIQUE KEY UK_BIZ_TASK_EXT_TASK (TASK_ID_)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_general_ci;

CREATE TABLE IF NOT EXISTS BIZ_COMM_SESSION_ (
    ID_ VARCHAR(64) NOT NULL,
    ROOT_TASK_ID_ VARCHAR(64) NOT NULL,
    INITIATOR_ VARCHAR(64) NOT NULL,
    INITIAL_CONTENT_ LONGTEXT NULL,
    STATUS_ VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    CURRENT_ROUND_ INT NULL DEFAULT 1,
    CREATE_TIME_ DATETIME(3) NULL DEFAULT CURRENT_TIMESTAMP(3),
    FINISH_TIME_ DATETIME(3) NULL,
    PRIMARY KEY (ID_)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_general_ci;

CREATE TABLE IF NOT EXISTS BIZ_COMM_TASK_ (
    ID_ VARCHAR(64) NOT NULL,
    SESSION_ID_ VARCHAR(64) NOT NULL,
    PARENT_COMM_TASK_ID_ VARCHAR(64) NULL,
    SOURCE_TASK_ID_ VARCHAR(64) NOT NULL,
    ROOT_TASK_ID_ VARCHAR(64) NOT NULL,
    SOURCE_TASK_DEF_KEY_ VARCHAR(64) NULL,
    TARGET_TYPE_ VARCHAR(16) NOT NULL,
    TARGET_ID_ VARCHAR(64) NOT NULL,
    TARGET_NAME_ VARCHAR(128) NULL,
    CONTENT_ LONGTEXT NULL,
    STATUS_ VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    REPLY_CONTENT_ LONGTEXT NULL,
    REPLY_USER_ID_ VARCHAR(64) NULL,
    REPLY_TIME_ DATETIME(3) NULL,
    WITHDRAW_TIME_ DATETIME(3) NULL,
    CAMUNDA_TASK_ID_ VARCHAR(64) NULL COMMENT '沟通旁路任务ID：收回/反馈/待办反查的唯一关联键',
    DEPT_PROC_INST_ID_ VARCHAR(64) NULL COMMENT '部门沟通子流程实例ID：TARGET_TYPE_ = DEPT 时写入，收回与主流程结束级联终止据此定位整个子流程',
    CREATE_TIME_ DATETIME(3) NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (ID_)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_general_ci;

CREATE TABLE IF NOT EXISTS BIZ_TASK_TRANSFER_ (
    ID_ VARCHAR(64) NOT NULL,
    TASK_ID_ VARCHAR(64) NOT NULL,
    PROC_INST_ID_ VARCHAR(64) NULL,
    TASK_DEF_KEY_ VARCHAR(64) NULL,
    TASK_NAME_ VARCHAR(255) NULL,
    FROM_USER_ID_ VARCHAR(64) NOT NULL,
    TO_USER_ID_ VARCHAR(64) NOT NULL,
    REASON_ VARCHAR(500) NULL,
    CREATE_TIME_ DATETIME(3) NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (ID_)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_general_ci;
