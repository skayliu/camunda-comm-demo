CREATE TABLE IF NOT EXISTS BIZ_TASK_DELEGATE_ (
    ID_ VARCHAR(64) NOT NULL,
    TASK_ID_ VARCHAR(64) NOT NULL,
    PROC_INST_ID_ VARCHAR(64) NULL,
    TASK_DEF_KEY_ VARCHAR(64) NULL,
    TASK_NAME_ VARCHAR(255) NULL,
    OWNER_USER_ID_ VARCHAR(64) NOT NULL,
    DELEGATE_USER_ID_ VARCHAR(64) NOT NULL,
    SOURCE_ VARCHAR(16) NOT NULL DEFAULT 'MANUAL',
    AGENT_RULE_ID_ VARCHAR(64) NULL,
    REASON_ VARCHAR(500) NULL,
    STATUS_ VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    RESOLVE_CONTENT_ LONGTEXT NULL,
    RESOLVE_TIME_ DATETIME(3) NULL,
    CREATE_TIME_ DATETIME(3) NULL DEFAULT CURRENT_TIMESTAMP(3),
    UPDATE_TIME_ DATETIME(3) NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (ID_)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_general_ci;

CREATE TABLE IF NOT EXISTS BIZ_AGENT_RULE_ (
    ID_ VARCHAR(64) NOT NULL,
    OWNER_USER_ID_ VARCHAR(64) NOT NULL,
    AGENT_USER_ID_ VARCHAR(64) NOT NULL,
    START_TIME_ DATETIME(3) NOT NULL,
    END_TIME_ DATETIME(3) NOT NULL,
    PROCESS_DEFINITION_KEYS_ VARCHAR(1000) NULL,
    IS_ENABLED_ TINYINT NOT NULL DEFAULT 1,
    CREATE_TIME_ DATETIME(3) NULL DEFAULT CURRENT_TIMESTAMP(3),
    UPDATE_TIME_ DATETIME(3) NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (ID_)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_general_ci;

CREATE INDEX IDX_BIZ_DELEGATE_TASK_TIME ON BIZ_TASK_DELEGATE_ (TASK_ID_, CREATE_TIME_);
CREATE INDEX IDX_BIZ_DELEGATE_OWNER_TIME ON BIZ_TASK_DELEGATE_ (OWNER_USER_ID_, CREATE_TIME_);
CREATE INDEX IDX_BIZ_DELEGATE_TGT_STATUS ON BIZ_TASK_DELEGATE_ (DELEGATE_USER_ID_, STATUS_);
CREATE INDEX IDX_BIZ_AGENT_OWNER_ENABLED ON BIZ_AGENT_RULE_ (OWNER_USER_ID_, IS_ENABLED_);
