-- 与 H2 版的三处差异：
--   1. 时间列 DATETIME(3)（TIMESTAMP 2038 溢出且随会话时区漂移）；
--   2. 大文本 LONGTEXT；
--   3. MySQL 不支持 CREATE INDEX IF NOT EXISTS，幂等性由 Flyway 版本表保证。
