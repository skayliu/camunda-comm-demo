-- 待办业务扩展表
CREATE TABLE IF NOT EXISTS BIZ_TASK_EXT_ (
    ID_ VARCHAR(64) PRIMARY KEY,
    TASK_ID_ VARCHAR(64) NOT NULL UNIQUE,
    PROC_INST_ID_ VARCHAR(64),
    ASSIGNEE_ VARCHAR(64),
    BIZ_STATUS_ VARCHAR(20) NOT NULL DEFAULT 'NORMAL',
    ACTIVE_SESSION_ID_ VARCHAR(64),
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 沟通会话表
CREATE TABLE IF NOT EXISTS BIZ_COMM_SESSION_ (
    ID_ VARCHAR(64) PRIMARY KEY,
    ROOT_TASK_ID_ VARCHAR(64) NOT NULL,
    INITIATOR_ VARCHAR(64) NOT NULL,
    INITIAL_CONTENT_ CLOB,
    STATUS_ VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    CURRENT_ROUND_ INT DEFAULT 1,
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FINISH_TIME_ TIMESTAMP
);

-- 沟通任务表
CREATE TABLE IF NOT EXISTS BIZ_COMM_TASK_ (
    ID_ VARCHAR(64) PRIMARY KEY,
    SESSION_ID_ VARCHAR(64) NOT NULL,
    PARENT_COMM_TASK_ID_ VARCHAR(64),
    SOURCE_TASK_ID_ VARCHAR(64) NOT NULL,
    ROOT_TASK_ID_ VARCHAR(64) NOT NULL,
    SOURCE_TASK_DEF_KEY_ VARCHAR(64),
    TARGET_TYPE_ VARCHAR(16) NOT NULL,
    TARGET_ID_ VARCHAR(64) NOT NULL,
    TARGET_NAME_ VARCHAR(128),
    CONTENT_ CLOB,
    STATUS_ VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    REPLY_CONTENT_ CLOB,
    REPLY_USER_ID_ VARCHAR(64),
    REPLY_TIME_ TIMESTAMP,
    WITHDRAW_TIME_ TIMESTAMP,
    -- 沟通旁路任务ID：收回/反馈/待办反查的唯一关联键
    CAMUNDA_TASK_ID_ VARCHAR(64),
    -- 部门沟通子流程实例ID：预留给 DEPT 类型沟通，当前恒为 NULL
    DEPT_PROC_INST_ID_ VARCHAR(64),
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 待办转办记录表：引擎只保留当前办理人，转办链只能落在业务表
CREATE TABLE IF NOT EXISTS BIZ_TASK_TRANSFER_ (
    ID_ VARCHAR(64) PRIMARY KEY,
    TASK_ID_ VARCHAR(64) NOT NULL,
    PROC_INST_ID_ VARCHAR(64),
    TASK_DEF_KEY_ VARCHAR(64),
    TASK_NAME_ VARCHAR(255),
    FROM_USER_ID_ VARCHAR(64) NOT NULL,
    TO_USER_ID_ VARCHAR(64) NOT NULL,
    REASON_ VARCHAR(500),
    CREATE_TIME_ TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_BIZ_TASK_EXT_TASK ON BIZ_TASK_EXT_(TASK_ID_);
CREATE INDEX IF NOT EXISTS IDX_BIZ_TASK_TRANSFER_TASK ON BIZ_TASK_TRANSFER_(TASK_ID_);
CREATE INDEX IF NOT EXISTS IDX_BIZ_TASK_TRANSFER_PROC ON BIZ_TASK_TRANSFER_(PROC_INST_ID_);
CREATE INDEX IF NOT EXISTS IDX_BIZ_COMM_SESSION_ROOT ON BIZ_COMM_SESSION_(ROOT_TASK_ID_);
CREATE INDEX IF NOT EXISTS IDX_BIZ_COMM_TASK_SESSION ON BIZ_COMM_TASK_(SESSION_ID_);
CREATE INDEX IF NOT EXISTS IDX_BIZ_COMM_TASK_PARENT ON BIZ_COMM_TASK_(PARENT_COMM_TASK_ID_);
CREATE INDEX IF NOT EXISTS IDX_BIZ_COMM_TASK_SOURCE ON BIZ_COMM_TASK_(SOURCE_TASK_ID_);
CREATE INDEX IF NOT EXISTS IDX_BIZ_COMM_TASK_SRC_KEY ON BIZ_COMM_TASK_(SOURCE_TASK_DEF_KEY_);
CREATE INDEX IF NOT EXISTS IDX_BIZ_COMM_TASK_CAMUNDA ON BIZ_COMM_TASK_(CAMUNDA_TASK_ID_);
